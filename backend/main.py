"""
FastAPI application for Project Black Knight.
Exposes clean, RESTful JSON endpoints for search, item retrieval,
random discovery, and metadata-driven browsing.
"""

from __future__ import annotations

import logging
from typing import Literal
from fastapi import FastAPI, HTTPException, Query, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse

from .schemas import (
    BrowseRequest,
    ItemDetail,
    MetadataCategoriesResponse,
    SearchRequest,
    SearchResponse,
)
from .services import (
    browse_by_metadata,
    get_item_by_id,
    get_metadata_categories,
    get_random_item,
    search_content,
)

logger = logging.getLogger("project_black_knight")
logging.basicConfig(level=logging.INFO)

app = FastAPI(
    title="Project Black Knight API",
    description="Intelligent search and retrieval engine for movies, anime, and books.",
    version="0.1.0",
)

# Enable CORS for local frontend communication (Vite default is 5173)
app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "http://localhost:5173",
        "http://127.0.0.1:5173",
        "http://localhost:3000",
        "http://127.0.0.1:3000",
        "*",
    ],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


@app.get("/health", tags=["Health"])
@app.get("/api/health", tags=["Health"])
def health_check():
    """Verify backend health and accessibility."""
    return {
        "status": "ok",
        "service": "Project Black Knight API",
        "version": "0.1.0",
    }


@app.post(
    "/search",
    response_model=SearchResponse,
    tags=["Search"],
)
@app.post(
    "/api/search",
    response_model=SearchResponse,
    tags=["Search"],
)
def search_endpoint(request: SearchRequest):
    """
    Execute natural-language search query across movies, anime, and books.
    Returns ranked search results in the exact order generated by the retrieval pipeline.
    """
    clean_query = request.query.strip()
    if not clean_query:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Search query cannot be empty or whitespace only.",
        )

    try:
        response = search_content(request)
        return response
    except ValueError as ve:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(ve),
        )
    except Exception as exc:
        logger.error(f"Search error: {exc}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="An error occurred while executing the search query. Please try again.",
        )


@app.get(
    "/items/{item_id}",
    response_model=ItemDetail,
    tags=["Items"],
)
@app.get(
    "/api/items/{item_id}",
    response_model=ItemDetail,
    tags=["Items"],
)
def get_item_endpoint(item_id: str):
    """
    Retrieve full metadata for an item by its canonical ID (e.g., 'movie_0', 'anime_24', 'book_100').
    """
    try:
        return get_item_by_id(item_id)
    except (KeyError, ValueError) as e:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=str(e),
        )
    except Exception as exc:
        logger.error(f"Item lookup error for {item_id}: {exc}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="An unexpected error occurred while retrieving item metadata.",
        )


@app.get(
    "/random",
    response_model=ItemDetail,
    tags=["Discovery"],
)
@app.get(
    "/api/random",
    response_model=ItemDetail,
    tags=["Discovery"],
)
def get_random_endpoint(
    domain: Literal["any", "movie", "anime", "book"] = Query(
        default="any",
        description="Filter domain for random selection (any, movie, anime, or book)",
    )
):
    """
    Uniformly select a real item from the requested catalog.
    Does not use LLM or retrieval ranking.
    """
    try:
        return get_random_item(domain=domain)
    except Exception as exc:
        logger.error(f"Random item error: {exc}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Unable to select a random item at this time.",
        )


@app.get(
    "/metadata/categories",
    response_model=MetadataCategoriesResponse,
    tags=["Metadata"],
)
@app.get(
    "/api/metadata/categories",
    response_model=MetadataCategoriesResponse,
    tags=["Metadata"],
)
def get_categories_endpoint():
    """
    Return available metadata categories (domains, genres, and release year ranges)
    derived directly from the underlying catalogs.
    """
    try:
        return get_metadata_categories()
    except Exception as exc:
        logger.error(f"Categories error: {exc}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to load metadata categories.",
        )


@app.post(
    "/browse",
    response_model=SearchResponse,
    tags=["Metadata"],
)
@app.post(
    "/api/browse",
    response_model=SearchResponse,
    tags=["Metadata"],
)
def browse_endpoint(request: BrowseRequest):
    """
    Filter items using metadata criteria (genre, domain, release year range)
    using the existing metadata-filtering logic.
    """
    try:
        return browse_by_metadata(request)
    except Exception as exc:
        logger.error(f"Browse error: {exc}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to browse metadata records.",
        )
