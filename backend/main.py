@app.get("/health", tags=["Health"])
@app.get("/api/health", tags=["Health"])
@app.get("/health/ready", tags=["Health"])
@app.get("/api/health/ready", tags=["Health"])
def readiness_check():
    """
    Verify application readiness by ensuring ChromaDB vector store collections are loaded.
    Returns HTTP 200 when ready; returns HTTP 503 Service Unavailable when indexing or loading.
    """
    is_ready, details = check_service_readiness()
    if not is_ready:
        logger.warning(f"Readiness check failed: {details}")
        return JSONResponse(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            content={
                "status": "not_ready",
                "service": "EZIO API",
                "version": "0.1.0",
                "detail": details,
            },
        )
    return {
        "status": "ok",
        "ready": True,
        "service": "EZIO API",
        "version": "0.1.0",
        "collections": details,
    }


@app.post(
    "/search",
    response_model=SearchResponse,
    tags=["Search"],
)
@app.post(
    "/api/search",
    response_model=SearchResponse,
    tags=["Search"],
)
def search_endpoint(request: SearchRequest):
    """
    Execute natural-language search query across movies, anime, and books.
    Returns ranked search results in the exact order generated by the retrieval pipeline.
    """
    clean_query = request.query.strip()
    if not clean_query:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Search query cannot be empty or whitespace only.",
        )

    try:
        response = search_content(request)
        return response
    except ValueError as ve:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(ve),
        )
    except Exception as exc:
        logger.error(f"Search error: {exc}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="An error occurred while executing the search query. Please try again.",
        )


@app.get(
    "/items/{item_id}",
    response_model=ItemDetail,
    tags=["Items"],
)
@app.get(
    "/api/items/{item_id}",
    response_model=ItemDetail,
    tags=["Items"],
)
def get_item_endpoint(item_id: str):
    """
    Retrieve full metadata for an item by its canonical ID (e.g., 'movie_0', 'anime_24', 'book_100').
    """
    try:
        return get_item_by_id(item_id)
    except (KeyError, ValueError) as e:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=str(e),
        )
    except Exception as exc:
        logger.error(f"Item lookup error for {item_id}: {exc}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="An unexpected error occurred while retrieving item metadata.",
        )


@app.get(
    "/random",
    response_model=ItemDetail,
    tags=["Discovery"],
)
@app.get(
    "/api/random",
    response_model=ItemDetail,
    tags=["Discovery"],
)
def get_random_endpoint(
    domain: Literal["any", "movie", "anime", "book"] = Query(
        default="any",
        description="Filter domain for random selection (any, movie, anime, or book)",
    )
):
    """
    Uniformly select a real item from the requested catalog.
    Does not use LLM or retrieval ranking.
    """
    try:
        return get_random_item(domain=domain)
    except Exception as exc:
        logger.error(f"Random item error: {exc}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Unable to select a random item at this time.",
        )


